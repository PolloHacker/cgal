"""
Run both Fine-Tuned SPT (SuperpointGraphSAGE) and Pointcept/Utonia (137.25M params)
on the three massive CFO_004 caves (96.6M to 199.1M points each):
  1. CFO_004_colorized-001   (input/CFO_004_colorized-001.ply,   123,973,474 pts)
  2. CFO_004_uncolorized-002 (input/CFO_004_uncolorized-002.ply, 199,092,445 pts)
  3. CFO_004_uncolorized-003 (input/CFO_004_uncolorized-003.ply,  96,582,285 pts)

Uses out-of-core chunked streaming (15M points/chunk) for P0 subsampling and
full-resolution cleaned PLY export so memory usage remains < 4 GB RAM and < 1.6 GB VRAM.
"""

